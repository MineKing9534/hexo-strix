def test_flags7_server_rebuild_hashes_match_rust_client_hashes():
    """The flags7 variant rebuilt with all three builder flags on must produce
    the SAME per-graph legal-order hashes as the Rust client (legal coords are
    flag-independent, so the flags0 client hashes apply)."""
    raw = _read_fixture("wire_states_request_flags7.bin")
    body, server_hashes = _read_forward_states_body(
        io.BytesIO(raw[6:]), 11,
        prune_empty_edges=True, threat_features=True, relative_stones=True,
    )
    assert body["node_dim"] == 11
    hash_bytes = _read_fixture("wire_states_legal_hashes.bin")
    client_hashes = list(struct.unpack(f"<{len(hash_bytes) // 8}Q", hash_bytes))
    assert list(server_hashes) == client_hashes


