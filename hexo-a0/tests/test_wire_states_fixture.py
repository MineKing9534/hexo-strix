"""Cross-language golden fixture for the MSG_FORWARD_STATES request wire (A3).

The byte streams under tests/fixtures/ are generated by the RUST client
encoder (`encode_forward_states_request` in
hexo-rs/hexo-mcts/src/inference_subprocess.rs, test
`wire_states_golden_fixture`) for fixed positions, and parsed here with the
real server-side parser. This pins encoder and parser to the same bytes:

- wire_states_request.bin       full request frame (6-byte header + body)
- wire_states_legal_hashes.bin  u64 LE per graph: the Rust CLIENT's FNV-1a
                                legal-order hash (compared against the
                                server's rebuilt-legal hashes below)

Regenerate (from the repo root) with:

    CARGO_TARGET_DIR=hexo-rs/target-a3 HEXO_REGEN_WIRE_FIXTURES=1 \
        cargo test -p hexo-mcts --manifest-path hexo-rs/Cargo.toml \
        wire_states_golden_fixture
"""

import io
import struct
from pathlib import Path

import torch

import hexo_rs
from hexo_a0.inference_server import (
    MAGIC,
    MSG_FORWARD,
    MSG_FORWARD_STATES,
    VERSION,
    _prepare_tensors,
    _read_forward_body,
    _read_forward_states_body,
    _states_request_frame,
    _unpack_hexkey,
)

from test_wire_states_parity import _collate_graph_body

FIXTURE_DIR = Path(__file__).parent / "fixtures"

# MUST stay in sync with FIXTURE_MOVES / FIXTURE_POINTS in
# hexo-rs/hexo-mcts/src/inference_subprocess.rs (wire_states_tests).
MOVES = [(1, 0), (0, 1), (2, 0), (1, 1), (-1, 2), (3, -1), (0, -2)]
SNAPSHOT_POINTS = [0, 1, 4, 7]
WIN_LENGTH, PLACEMENT_RADIUS, MAX_MOVES = 6, 8, 200
NODE_DIM = 8  # builder_flags = 0 (no prune / threat / relative)


def _replay(n_moves: int) -> "hexo_rs.GameState":
    config = hexo_rs.GameConfig(WIN_LENGTH, PLACEMENT_RADIUS, MAX_MOVES)
    game = hexo_rs.GameState(config)
    for q, r in MOVES[:n_moves]:
        game.apply_move(q, r)
    return game


def _read_fixture(name: str = "wire_states_request.bin") -> bytes:
    """Read a checked-in golden fixture, FAILING with a clear message when it is
    missing (rather than silently regenerating — the byte pin is meaningless if
    the test can recreate it). The Rust side owns generation; regenerate with
    HEXO_REGEN_WIRE_FIXTURES=1 (see module docstring)."""
    path = FIXTURE_DIR / name
    assert path.exists(), (
        f"missing golden fixture {path}; regenerate with HEXO_REGEN_WIRE_FIXTURES=1 "
        "cargo test -p hexo-mcts wire_states_golden_fixture (the .bin fixtures are "
        "committed — check .gitignore's negation if they vanished)"
    )
    return path.read_bytes()


def test_rust_request_frame_fields_match_replayed_states():
    raw = _read_fixture()
    magic, version, msg_type = struct.unpack("<IBB", raw[:6])
    assert magic == MAGIC
    assert version == VERSION
    assert msg_type == MSG_FORWARD_STATES

    stdin = io.BytesIO(raw[6:])
    (num_graphs, win_length, placement_radius, max_moves,
     builder_flags, node_dim, graphs) = _states_request_frame(stdin)
    assert stdin.read() == b"", "frame must consume the body exactly"

    assert num_graphs == len(SNAPSHOT_POINTS)
    assert win_length == WIN_LENGTH
    assert placement_radius == PLACEMENT_RADIUS
    assert max_moves == MAX_MOVES
    assert builder_flags == 0
    assert node_dim == NODE_DIM

    for (p1_keys, p2_keys, cur, mr, num_legal), k in zip(graphs, SNAPSHOT_POINTS):
        game = _replay(k)

        # Stone sets round-trip through the canonical HexKey packing.
        expected_p1 = sorted(c for c, p in game.placed_stones() if p == "P1")
        expected_p2 = sorted(c for c, p in game.placed_stones() if p == "P2")
        assert sorted(_unpack_hexkey(key) for key in p1_keys) == expected_p1
        assert sorted(_unpack_hexkey(key) for key in p2_keys) == expected_p2
        # The Rust encoder emits keys sorted ascending (deterministic bytes;
        # signed-key order == lexicographic (q, r) order).
        assert list(p1_keys) == sorted(p1_keys)
        assert list(p2_keys) == sorted(p2_keys)

        assert cur == (0 if game.current_player() == "P1" else 1)
        assert mr == game.moves_remaining_this_turn()
        assert num_legal == len(game.legal_moves())


