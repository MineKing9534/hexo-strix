# Dedicated tight-radius config for the graph fixture (the graph wire carries
# full features+edges, so the states fixture's radius-8 positions would bloat
# the committed .bin to ~1 MB). MUST stay in sync with GRAPH_FIXTURE_* in
# hexo-rs/hexo-mcts/src/inference_subprocess.rs (wire_states_tests).
GRAPH_MOVES = [(1, 0), (0, 1), (-1, 1), (1, -1), (0, -1)]
GRAPH_POINTS = [0, 1, 3, 5]
GRAPH_WIN_LENGTH, GRAPH_PLACEMENT_RADIUS, GRAPH_MAX_MOVES = 5, 2, 200


def _replay_graph(n_moves: int) -> "hexo_rs.GameState":
    config = hexo_rs.GameConfig(
        GRAPH_WIN_LENGTH, GRAPH_PLACEMENT_RADIUS, GRAPH_MAX_MOVES)
    game = hexo_rs.GameState(config)
    for q, r in GRAPH_MOVES[:n_moves]:
        game.apply_move(q, r)
    return game


def test_rust_graph_request_matches_python_collation():
    """TQ2-W1: the MSG_FORWARD request bytes emitted by the REAL Rust client
    encoder (`encode_forward_request`, which `forward_graphs` calls) must parse
    via `_read_forward_body` into tensors identical to the same positions built
    through hexo_rs single-graph collation — pinning the graph wire across
    languages (the states fixtures pin the states wire; this pins the legacy one).
    """
    raw = _read_fixture("wire_graph_request.bin")
    magic, version, msg_type = struct.unpack("<IBB", raw[:6])
    assert magic == MAGIC
    assert version == VERSION
    assert msg_type == MSG_FORWARD

    rust_body = _read_forward_body(io.BytesIO(raw[6:]), expected_node_dim=NODE_DIM)

    # Same positions, built through the Python-called hexo_rs builder and
    # collated exactly like the Rust encoder lays out the wire body.
    games = [_replay_graph(k) for k in GRAPH_POINTS]
    py_body = _read_forward_body(
        io.BytesIO(_collate_graph_body(games, NODE_DIM)), expected_node_dim=NODE_DIM,
    )

    # Framing / scalar fields agree.
    for key in ("total_nodes", "total_edges", "num_graphs", "has_edge_attr",
                "node_dim"):
        assert rust_body[key] == py_body[key], f"body field {key!r}"

    # Tensors equal through the unmodified _prepare_tensors.
    cpu = torch.device("cpu")
    r_tensors, r_real_n = _prepare_tensors(rust_body, cpu, None, padded=False)
    p_tensors, p_real_n = _prepare_tensors(py_body, cpu, None, padded=False)
    assert r_real_n == p_real_n == len(GRAPH_POINTS)
    assert len(r_tensors) == len(p_tensors)
    for i, (rv, pv) in enumerate(zip(r_tensors, p_tensors)):
        if isinstance(pv, int):  # num_graphs
            assert rv == pv, f"tensor slot {i} (num_graphs) differs"
            continue
        assert rv.dtype == pv.dtype and rv.shape == pv.shape, f"tensor slot {i}"
        assert torch.equal(rv, pv), f"tensor slot {i} values differ"


def test_server_rebuild_hashes_match_rust_client_hashes():
    """End-to-end order guard: the server parses the Rust-encoded request,
    rebuilds the graphs, and its per-graph FNV-1a legal-coord hashes must
    equal the hashes the Rust CLIENT computed from its own legal_moves()
    snapshots (wire_states_legal_hashes.bin)."""
    raw = _read_fixture()
    result = _read_forward_states_body(io.BytesIO(raw[6:]), NODE_DIM)
    assert result is not None, "non-empty request must not parse as a probe"
    body, server_hashes = result
    assert body["num_graphs"] == len(SNAPSHOT_POINTS)
    assert body["node_dim"] == NODE_DIM

    hash_bytes = _read_fixture("wire_states_legal_hashes.bin")
    client_hashes = list(
        struct.unpack(f"<{len(hash_bytes) // 8}Q", hash_bytes)
    )
    assert len(client_hashes) == len(SNAPSHOT_POINTS)
    assert list(server_hashes) == client_hashes, (
        "legal-order FNV divergence between the Rust client snapshot and the "
        "server rebuild — the states wire's order guard would trip"
    )
